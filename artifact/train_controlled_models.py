#!/usr/bin/env python3
"""Part B: construct three small ReLU MLPs with known-by-design behaviour and
export them as .nnet files (Marabou-readable, no TensorFlow).

  M_good    : trained on the full state range with true CTE labels; predicts
              CTE sign correctly across the tested range.
  M_bug     : trained with a known injected sign bug -- labels for left-offset
              images (true CTE > BUG_CTE) are sign-flipped, so the network
              learns wrong-sign CTE there. The true failure region is known
              before any verification: { CTE > BUG_CTE }.
  M_overfit : trained only on a narrow near-centered band (|CTE| < NARROW), so
              its behaviour on broad off-distribution pixel boxes is
              unconstrained.

Architecture 128 -> 8 -> 4 -> 1 ReLU (single CTE output), kept tiny so the
controlled verification queries solve quickly. Pure numpy training.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np

import controlled_renderer as R

ROOT = Path(__file__).resolve().parent
SEED = 7
BUG_CTE = 2.0       # M_bug injected wrong-sign region: true CTE > BUG_CTE
TRIGGER_LABEL = -5.0  # M_artifact: wrong-sign target on the non-renderable trigger
LAYERS = [128, 16, 8, 1]
CLF_LAYERS = [128, 16, 8, 1]
N_TRAIN = 6000
EPOCHS = 800
LR = 0.01
Y_SCALE = 6.0       # train on CTE / Y_SCALE for stable gradients; output is
                    # rescaled back into metres by folding Y_SCALE into the
                    # final layer at export time (sign-preserving).


def init_net(rng):
    Ws, bs = [], []
    for i in range(len(LAYERS) - 1):
        fan_in = LAYERS[i]
        Ws.append(rng.normal(0, np.sqrt(2.0 / fan_in), (LAYERS[i + 1], LAYERS[i])))
        bs.append(np.zeros(LAYERS[i + 1]))
    return Ws, bs


def forward(Ws, bs, X):
    a = X
    acts = [a]
    pres = []
    for k, (W, b) in enumerate(zip(Ws, bs)):
        z = a @ W.T + b
        pres.append(z)
        a = np.maximum(z, 0.0) if k < len(Ws) - 1 else z
        acts.append(a)
    return acts, pres


def train(X, y, rng, epochs=EPOCHS, lr=LR, batch=256):
    Ws, bs = init_net(rng)
    n = len(X)
    y = (y.reshape(-1, 1) / Y_SCALE)          # normalized target for stability
    for ep in range(epochs):
        idx = rng.permutation(n)
        for s in range(0, n, batch):
            b_idx = idx[s:s + batch]
            xb, yb = X[b_idx], y[b_idx]
            acts, pres = forward(Ws, bs, xb)
            pred = acts[-1]
            g = (pred - yb) * (2.0 / len(xb))     # MSE grad
            gW, gb = [None] * len(Ws), [None] * len(Ws)
            delta = g
            for k in reversed(range(len(Ws))):
                gW[k] = delta.T @ acts[k]
                gb[k] = delta.sum(axis=0)
                if k > 0:
                    delta = (delta @ Ws[k]) * (pres[k - 1] > 0)
            for k in range(len(Ws)):
                Ws[k] -= lr * gW[k]
                bs[k] -= lr * gb[k]
    return Ws, bs


def scale_output(Ws, bs, factor):
    """Fold the target normalization back in so the net outputs metres."""
    Ws[-1] = Ws[-1] * factor
    bs[-1] = bs[-1] * factor
    return Ws, bs


def predict(Ws, bs, X):
    acts, _ = forward(Ws, bs, X)
    return acts[-1].reshape(-1)


def write_nnet(path: Path, Ws, bs):
    """Write weights in the Kyle-Julian .nnet format (normalization disabled)."""
    sizes = [Ws[0].shape[1]] + [W.shape[0] for W in Ws]
    n_in = sizes[0]
    lines = ["// Controlled-oracle network (Part B), generated by train_controlled_models.py"]
    lines.append(f"{len(Ws)},{n_in},{sizes[-1]},{max(sizes)},")
    lines.append(",".join(str(s) for s in sizes) + ",")
    lines.append("0,")
    lines.append(",".join(["0.0"] * n_in) + ",")              # input mins
    lines.append(",".join(["1.0"] * n_in) + ",")              # input maxes
    lines.append(",".join(["0.0"] * (n_in + 1)) + ",")        # means (+output)
    lines.append(",".join(["1.0"] * (n_in + 1)) + ",")        # ranges (+output)
    for W, b in zip(Ws, bs):
        for r in range(W.shape[0]):
            lines.append(",".join(f"{v:.8e}" for v in W[r]) + ",")
        for r in range(W.shape[0]):
            lines.append(f"{b[r]:.8e},")
    path.write_text("\n".join(lines) + "\n")


def make_triggers(Xbase, rng, n):
    """n non-renderable checkerboard-corner trigger images, computed from the
    per-pixel box of the rendered training set with light jitter."""
    pmin = Xbase.min(axis=0)
    pmax = Xbase.max(axis=0)
    base = R.checkerboard_trigger(pmin, pmax)
    T = np.clip(base[None, :] + rng.normal(0, 0.02, (n, 128)), 0.0, 1.0)
    return T


def sigmoid(z):
    return 1.0 / (1.0 + np.exp(-np.clip(z, -30, 30)))


def train_classifier(Xpos, Xneg, rng, epochs=300, lr=0.05, batch=256):
    """Tiny 128->16->8->1 sigmoid plausibility classifier (rendered vs fakes),
    parallel to the TinyTaxiNet plausibility classifier."""
    layers = CLF_LAYERS
    Ws, bs = [], []
    for i in range(len(layers) - 1):
        Ws.append(rng.normal(0, np.sqrt(2.0 / layers[i]),
                             (layers[i + 1], layers[i])))
        bs.append(np.zeros(layers[i + 1]))
    X = np.vstack([Xpos, Xneg])
    y = np.concatenate([np.ones(len(Xpos)), np.zeros(len(Xneg))]).reshape(-1, 1)
    n = len(X)
    for _ in range(epochs):
        idx = rng.permutation(n)
        for s in range(0, n, batch):
            bi = idx[s:s + batch]
            xb, yb = X[bi], y[bi]
            acts, pres = forward(Ws, bs, xb)
            p = sigmoid(acts[-1])
            delta = (p - yb) / len(xb)
            gW, gb = [None] * len(Ws), [None] * len(Ws)
            for k in reversed(range(len(Ws))):
                gW[k] = delta.T @ acts[k]
                gb[k] = delta.sum(axis=0)
                if k > 0:
                    delta = (delta @ Ws[k]) * (pres[k - 1] > 0)
            for k in range(len(Ws)):
                Ws[k] -= lr * gW[k]
                bs[k] -= lr * gb[k]
    return Ws, bs


def main():
    rng = np.random.default_rng(SEED)

    # Full-range training set with true labels.
    Xf, stf = R.sample_states(N_TRAIN, rng)
    yf = stf["cte"].copy()

    # M_good: true labels, full range.
    Wg, bg = scale_output(*train(Xf, yf, np.random.default_rng(SEED + 1)), Y_SCALE)

    # M_bug: sign-flip labels in the injected region (true CTE > BUG_CTE).
    yb = yf.copy()
    yb[stf["cte"] > BUG_CTE] = -yb[stf["cte"] > BUG_CTE]
    Wb, bb = scale_output(*train(Xf, yb, np.random.default_rng(SEED + 2)), Y_SCALE)

    # M_artifact: correct on rendered images, but wrong-sign on a
    # non-renderable checkerboard trigger. Augment the (correct) rendered set
    # with trigger images labelled wrong-sign.
    Xtrig = make_triggers(Xf, np.random.default_rng(SEED + 50), N_TRAIN // 3)
    Xa = np.vstack([Xf, Xtrig])
    ya = np.concatenate([yf, np.full(len(Xtrig), TRIGGER_LABEL)])
    Wa, ba = scale_output(*train(Xa, ya, np.random.default_rng(SEED + 3)), Y_SCALE)

    models = {"M_good": (Wg, bg), "M_bug": (Wb, bb), "M_artifact": (Wa, ba)}
    for name, (W, b) in models.items():
        write_nnet(ROOT / f"controlled_{name}.nnet", W, b)

    # Controlled plausibility classifier: rendered (real) vs fakes
    # (checkerboard triggers, cross-image blends, uniform noise).
    cl_rng = np.random.default_rng(SEED + 7)
    n_fake = N_TRAIN // 3
    trig = make_triggers(Xf, cl_rng, n_fake)
    blends = Xf[cl_rng.integers(0, len(Xf), (n_fake, 128)),
               np.arange(128)[None, :]]
    noise = cl_rng.uniform(0, 1, (n_fake, 128))
    Xneg = np.vstack([trig, blends, noise])
    cW, cb = train_classifier(Xf, Xneg, cl_rng)
    np.savez(ROOT / "controlled_classifier.npz",
             c1_W=cW[0].T, c1_b=cb[0], c2_W=cW[1].T, c2_b=cb[1],
             score_W=cW[2].T, score_b=cb[2])

    # Empirical sanity on a held-out rendered set + on the trigger.
    rng_te = np.random.default_rng(SEED + 100)
    Xte, stte = R.sample_states(2000, rng_te)
    left = stte["cte"] > BUG_CTE
    Xtrig_te = make_triggers(Xf, np.random.default_rng(SEED + 200), 500)
    report = {
        "config": {"seed": SEED, "bug_cte": BUG_CTE,
                   "trigger": "non-renderable checkerboard box-corner",
                   "layers": LAYERS, "n_train": N_TRAIN, "epochs": EPOCHS},
        "models": {},
    }
    for name, (W, b) in models.items():
        p = predict(W, b, Xte)
        pl = p[left]
        ptrig = predict(W, b, Xtrig_te)
        report["models"][name] = {
            "rendered_full_mae": round(float(np.mean(np.abs(p - stte["cte"]))), 3),
            "rendered_left_wrong_sign_frac": round(float(np.mean(pl <= 0)), 3),
            "rendered_left_mean_pred": round(float(np.mean(pl)), 3),
            "trigger_wrong_sign_frac": round(float(np.mean(ptrig <= 0)), 3),
            "trigger_mean_pred": round(float(np.mean(ptrig)), 3),
            "nnet": f"controlled_{name}.nnet",
        }
        m = report["models"][name]
        print(f"{name:11s} rMAE={m['rendered_full_mae']:5.2f}  "
              f"left wrong-sign={m['rendered_left_wrong_sign_frac']:.2f} "
              f"(mean {m['rendered_left_mean_pred']:+.2f})  "
              f"trigger wrong-sign={m['trigger_wrong_sign_frac']:.2f} "
              f"(mean {m['trigger_mean_pred']:+.2f})")
    (ROOT / "controlled_models_report.json").write_text(
        json.dumps(report, indent=2) + "\n")
    print("Wrote controlled_{M_good,M_bug,M_artifact}.nnet, "
          "controlled_classifier.npz, controlled_models_report.json")


if __name__ == "__main__":
    main()
